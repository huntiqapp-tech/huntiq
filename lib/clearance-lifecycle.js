(function(root,factory){const api=factory();if(typeof module==='object'&&module.exports)module.exports=api;root.HuntIQClearanceLifecycle=api;})(typeof globalThis!=='undefined'?globalThis:this,function(){
'use strict';
const clamp=(v,min=0,max=1)=>Math.min(max,Math.max(min,Number(v)||0));
const num=v=>Number.isFinite(Number(v))?Number(v):null;
function assessClearanceLifecycle(input={}){
  const history=input.history||input.historyAssessment||{};
  const anomaly=input.anomaly||{};
  const resale=input.resale||{};
  const economics=input.economics||{};
  const momentum=input.momentum||input.opportunityMomentum||{};
  const persistenceDays=Math.max(0,num(input.persistenceDays==null?momentum.persistenceDays:input.persistenceDays)||0);
  const confirmations=Math.max(0,Math.round(num(input.confirmations==null?momentum.confirmations:input.confirmations)||0));
  const retailerClearance=Boolean(input.retailerClearance||input.clearanceMarked||history.clearanceMarked);
  const terminalSignal=Boolean(input.terminalClearance||input.discontinued||history.discontinued);
  const historyCoverage=num(history.historyCoverageScore==null?history.confidence:history.historyCoverageScore);
  const dropPct=num(anomaly.dropPct);
  const anomalyScore=num(anomaly.score);
  const anomalyConfidence=num(anomaly.confidence);
  const resaleTrendPct=num(momentum.resaleTrendPct==null?resale.resaleTrendPct:momentum.resaleTrendPct);
  const sellThrough=num(resale.sellThroughRate==null?resale.sellThrough:resale.sellThroughRate);
  let stage='fresh-markdown';
  if(retailerClearance&&(terminalSignal||persistenceDays>=21))stage='terminal-clearance';
  else if(persistenceDays>=21&&confirmations>=4)stage='normalized-low-price';
  else if(persistenceDays>=7&&confirmations>=3)stage='established-markdown';
  const cautions=[];const blockers=[];
  let anomalyMultiplier=1;
  if(stage==='established-markdown')anomalyMultiplier=.85;
  if(stage==='normalized-low-price')anomalyMultiplier=.55;
  if(stage==='terminal-clearance')anomalyMultiplier=.75;
  if(historyCoverage!=null&&historyCoverage<50){anomalyMultiplier*=.85;cautions.push('price-history coverage is thin for lifecycle classification');}
  if(stage==='normalized-low-price')cautions.push('persistent retailer pricing increasingly resembles a new normal price rather than a fresh anomaly');
  if(stage==='terminal-clearance')cautions.push('retailer-marked terminal clearance can create sell-through pressure as multiple buyers source the same item');
  const adjustedAnomalyScore=anomalyScore==null?null:Math.round(anomalyScore*anomalyMultiplier);
  const adjustedAnomalyConfidence=anomalyConfidence==null?null:Math.round(anomalyConfidence*anomalyMultiplier);
  let resaleMultiplier=1;
  if(stage==='terminal-clearance')resaleMultiplier*=.9;
  if(stage==='normalized-low-price')resaleMultiplier*=.94;
  if(resaleTrendPct!=null&&resaleTrendPct<=-10)resaleMultiplier*=clamp(1-Math.min(.2,Math.abs(resaleTrendPct)/100),.75,1);
  if(sellThrough!=null&&sellThrough<35)resaleMultiplier*=.9;
  const expectedResale=num(resale.expectedPrice==null?(resale.median30d==null?resale.median:resale.median30d):resale.expectedPrice);
  const lifecycleAdjustedResale=expectedResale==null?null:+(expectedResale*resaleMultiplier).toFixed(2);
  const profit=num(economics.profit),roi=num(economics.roi);
  const economicsMultiplier=clamp(.55+.45*resaleMultiplier,.5,1);
  const lifecycleAdjustedProfit=profit==null?null:+(profit*economicsMultiplier).toFixed(2);
  const lifecycleAdjustedRoi=roi==null?null:+(roi*economicsMultiplier).toFixed(1);
  if(stage==='normalized-low-price'&&adjustedAnomalyConfidence!=null&&adjustedAnomalyConfidence<45)blockers.push('persistent low price no longer clears fresh-anomaly confidence');
  if(lifecycleAdjustedRoi!=null&&lifecycleAdjustedRoi<10)blockers.push('lifecycle-adjusted ROI is below the safety floor');
  if(stage==='terminal-clearance'&&sellThrough!=null&&sellThrough<25)blockers.push('terminal clearance has weak resale sell-through');
  let alertPriority='instant';
  if(blockers.length)alertPriority='digest';
  else if(stage==='established-markdown'||stage==='terminal-clearance'||persistenceDays>=7)alertPriority='standard';
  const alertEligible=!blockers.length;
  return{stage,retailerClearance,terminalSignal,persistenceDays:+persistenceDays.toFixed(1),confirmations,dropPct,anomalyMultiplier:+anomalyMultiplier.toFixed(3),adjustedAnomalyScore,adjustedAnomalyConfidence,resaleTrendPct,sellThrough,resaleMultiplier:+resaleMultiplier.toFixed(3),lifecycleAdjustedResale,economicsMultiplier:+economicsMultiplier.toFixed(3),lifecycleAdjustedProfit,lifecycleAdjustedRoi,alertEligible,alertPriority,blockers,cautions,method:'retailer-clearance-plus-price-persistence-plus-resale-pressure'};
}
return{assessClearanceLifecycle};
});